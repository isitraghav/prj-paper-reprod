"""ELDDS1400C5 (Roboflow v1, yolov5 format) -> 6-class lists + data.yaml for P2.

The Roboflow export lists 11 names. Ids 0-5 are the paper's 6 classes (Fig. 2: Examined +
5 defect categories). Ids 6-10 occur only in 2 train images (panel_04/panel_10 5 s
exposures) that carry no paper-class label at all; those images are excluded, giving
1186 train / 190 test (paper: 1187 / 190). Labels are used in place (ids 0-5 unchanged).

Committed split files hold dataset-relative names; per machine, absolute-path lists and
data.yaml are written into --dst (gitignored). There is no val split, so val = test, as
in the paper (train/test only).

usage: python -I prep_eldds.py --src datasets/raw/ELDDS1400C5 --dst datasets/eldds_yolo \
           --splits datasets/splits/eldds1400c5
"""
import argparse
from collections import Counter
from pathlib import Path

NAMES = ['Examined', 'ShortCircuitString', 'ShortCircuitCell-LowPowerCell', 'Crack', 'MicroCrack', 'OtherError']


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--src', required=True)
    ap.add_argument('--dst', required=True)
    ap.add_argument('--splits', required=True)
    a = ap.parse_args()
    src, dst, sp = Path(a.src).resolve(), Path(a.dst).resolve(), Path(a.splits)
    dst.mkdir(parents=True, exist_ok=True)

    lists = {}
    for s in ('train', 'test'):
        keep, drop = [], []
        for im in sorted((src / s / 'images').glob('*.jpg')):
            lab = src / s / 'labels' / (im.stem + '.txt')
            ids = [int(l.split()[0]) for l in lab.read_text().splitlines() if l.strip()] if lab.exists() else []
            (drop if any(i > 5 for i in ids) else keep).append(f'{s}/images/{im.name}')
            if any(i > 5 for i in ids) and any(i <= 5 for i in ids):
                raise SystemExit(f'{im.name} mixes paper and stray classes; handle explicitly')
        lists[s] = keep
        print(f'{s}: keep {len(keep)}, drop {len(drop)} {[d.split("/")[-1][:40] for d in drop]}')

    if (sp / 'train.txt').exists():
        frozen = {s: (sp / f'{s}.txt').read_text().split() for s in ('train', 'test')}
        assert frozen == lists, 'frozen split differs from what the raw data gives'
        print(f'frozen split in {sp} matches')
    else:
        sp.mkdir(parents=True, exist_ok=True)
        for s, L in lists.items():
            (sp / f'{s}.txt').write_text(''.join(x + '\n' for x in L))
        print(f'wrote split to {sp}')

    for s, L in lists.items():
        (dst / f'{s}.txt').write_text(''.join((src / x).as_posix() + '\n' for x in L))
        c = Counter(int(l.split()[0]) for x in L
                    for l in (src / x.replace('/images/', '/labels/')).with_suffix('.txt').read_text().splitlines() if l.strip())
        print(f'  {s} boxes: ' + ', '.join(f'{NAMES[k]}={c[k]}' for k in range(6)))
    (dst / 'data.yaml').write_text(
        f'# generated by code/repro/prep_eldds.py from {sp.as_posix()} -- do not edit\n'
        f'path: {dst.as_posix()}\ntrain: {(dst / "train.txt").as_posix()}\n'
        f'val: {(dst / "test.txt").as_posix()}\ntest: {(dst / "test.txt").as_posix()}\n'
        f'nc: {len(NAMES)}\nnames: {NAMES}\n')
    print((dst / 'data.yaml').read_text())


if __name__ == '__main__':
    main()
