"""Compare our three datasets with what each paper states (counts only; reads the raw downloads and our frozen splits).

P1 PV-Multi-Defect: images, split, boxes per class vs Fig. 5 (4235 boxes, shares), byte-identical duplicate images.
P2 ELDDS1400C5: images per split vs the text (1187 / 190), boxes per class and split vs Fig. 2.
P3 ELPV: cells per module type x label x split vs Table 3.

usage (repo root): envs/p1/Scripts/python.exe -I code/repro/check_datasets.py   -> results/dataset_check.md
"""
import glob
import hashlib
import sys
import xml.etree.ElementTree as ET
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
out = ['# Dataset check: ours vs what each paper states', '',
       'Generated by `code/repro/check_datasets.py`. Counts only.', '']


def row(*c):
    out.append('| ' + ' | '.join(str(x) for x in c) + ' |')


# ---- P1
pv = ROOT / 'datasets/raw/PV-Multi-Defect'
imgs = sorted(p for p in glob.glob(str(pv / 'JPEGImages/img*.jpg')))
split = {s: [l.strip() for l in open(ROOT / f'datasets/splits/pv_multi_defect/{s}.txt') if l.strip()] for s in ('train', 'val')}
boxes = Counter()
for x in glob.glob(str(pv / 'Annotations/*.xml')):
    boxes.update(o.find('name').text.strip() for o in ET.parse(x).getroot().iter('object'))
md5 = defaultdict(list)
for p in imgs:
    md5[hashlib.md5(open(p, 'rb').read()).hexdigest()].append(p)
dups = sum(len(v) > 1 for v in md5.values())
fig5 = {'hot_spot': 49.09, 'scratch': 36.62, 'black_border': 6.02, 'no_electricity': 4.28, 'broken': 3.99}
T = sum(boxes.values())
out += ['## P1 PV-Multi-Defect (Li et al. 2023)', '', '| Item | Paper | Ours |', '|---|---|---|']
row('images (600 x 600)', 1108, len(imgs))
row('train / val', '886 / 222 (membership unpublished)', f"{len(split['train'])} / {len(split['val'])} (re-created, seed 0)")
row('boxes', 4235, T)
for k, v in fig5.items():
    row(f'  {k}', f'{v:.2f} % (≈ {round(4235 * v / 100)})', f'{100 * boxes[k] / T:.2f} % ({boxes[k]})')
row('byte-identical duplicate image groups', 'not mentioned', dups)
out.append('')

# ---- P2
el = ROOT / 'datasets/raw/ELDDS1400C5'
names = ['Examined', 'ShortCircuitString', 'ShortCircuitCell', 'Crack', 'MicroCrack', 'OtherError']
fig2 = {'Examined': (1240, 138), 'ShortCircuitString': (468, 2), 'ShortCircuitCell': (681, 20), 'Crack': (461, 70),
        'MicroCrack': (10043, 998), 'OtherError': (2154, 87)}  # Fig. 2 bars; OtherError is labelled "DARKSPOT" there
cnt, nimg = {}, {}
for s in ('train', 'test'):
    fs = glob.glob(str(el / s / 'labels/*.txt'))
    nimg[s] = len(fs)
    c = Counter()
    for f in fs:
        c.update(int(l.split()[0]) for l in open(f) if l.strip())
    cnt[s] = c
used = {s: sum(1 for l in open(ROOT / f'datasets/eldds_yolo/{s}.txt') if l.strip()) for s in ('train', 'test')}
out += ['## P2 ELDDS1400C5 (Mazen et al. 2023)', '', '| Item | Paper text | Paper Fig. 2 (train / test) | Ours, Roboflow v1 (train / test) |',
        '|---|---|---|---|']
row('images', '1187 / 190', f"{sum(fig2['Examined'])} total (Examined boxes 1240 / 138)",
    f"{nimg['train']} / {nimg['test']}; used {used['train']} / {used['test']}")
for i, n in enumerate(names):
    a, b = fig2[n]
    row(f'  {n} boxes', '', f'{a} / {b} (total {a + b})', f"{cnt['train'][i]} / {cnt['test'][i]} (total {cnt['train'][i] + cnt['test'][i]})")
extra = sum(v for k, v in cnt['train'].items() if k > 5)
row('  other Roboflow ids 6-10', '', '', f'{extra} boxes in 2 train images (excluded)')
out.append('')

# ---- P3
lab = {}
for l in open(ROOT / 'datasets/raw/elpv-dataset/src/elpv_dataset/data/labels.csv'):
    if l.strip():
        p, v, t = l.split()
        lab[p] = (round(float(v) * 3), t)
t3 = {('train', 'mono'): [438, 87, 41, 249], ('train', 'poly'): [683, 132, 37, 301],
      ('test', 'mono'): [150, 30, 15, 64], ('test', 'poly'): [237, 46, 13, 101]}
out += ['## P3 ELPV (Deitsch et al. 2019)', '', '| Split | Type | Paper Table 3 (p = 0 / 1/3 / 2/3 / 1) | Ours | Match |', '|---|---|---|---|---|']
for s in ('train', 'test'):
    c = Counter(lab[k] for k in open(ROOT / f'datasets/splits/elpv/{s}.txt').read().split())
    for t in ('mono', 'poly'):
        ours = [c[(i, t)] for i in range(4)]
        row(s, t, ' / '.join(map(str, t3[(s, t)])), ' / '.join(map(str, ours)), '✅' if ours == t3[(s, t)] else '❌')
row('all', '', 2624, len(lab), '✅' if len(lab) == 2624 else '❌')

(ROOT / 'results/dataset_check.md').write_text('\n'.join(out) + '\n', encoding='utf-8')
sys.stdout.reconfigure(encoding='utf-8')
print('\n'.join(out))
