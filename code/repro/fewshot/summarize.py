"""Few-shot transfer results (runs from make_fewshot.py): target mAP@.5 vs number of labelled target images, starting
from the other paper's trained model ("src") or from COCO. Per-class AP is read from each run's final validation in
its training log; "defect mAP" averages the defect classes only (ELDDS: without 'Examined').

usage (repo root): envs/p3cnn/Scripts/python.exe -I code/repro/fewshot/summarize.py
-> results/fewshot/summary.md, summary.json, results/cross/figs/fig11_fewshot.png
"""
import json
import re
import sys
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt  # noqa: E402
from matplotlib.lines import Line2D  # noqa: E402

ROOT = Path(__file__).resolve().parents[3]
FS = ROOT / 'results/fewshot'
sys.stdout.reconfigure(encoding='utf-8')
NS = (10, 50, 100)
CLASSES = {'pv': ['broken', 'hot_spot', 'black_border', 'scratch', 'no_electricity'],
           'eldds': ['ShortCircuitString', 'ShortCircuitCell-LowPowerCell', 'Crack', 'MicroCrack', 'OtherError']}
# home models on their own full training set (same evaluation split; defect classes only), for reference
HOME = {'pv': ('P1 YOLOv5s, 886 images, 960 px', 0.856), 'eldds': ('P2 YOLOv5s, 1186 images, 640 px', 0.698)}
SRC = {'pv': 'P2 YOLOv5s (trained on ELDDS)', 'eldds': 'P1 YOLOv5s (trained on PV-Multi-Defect)'}
ROW = re.compile(r'^\s+(\S+)\s+\d+\s+\d+\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s+([\d.]+)\s*$')


def final_val(log):
    """Last block of per-class rows in the log -> {class: AP50}, plus 'all'."""
    lines = re.sub(r'\x1b\[[0-9;]*m', '', log.read_text(encoding='utf-8', errors='replace').replace('\r', '\n')).splitlines()
    starts = [i for i, l in enumerate(lines) if ROW.match(l) and ROW.match(l).group(1) == 'all']
    if not starts:
        return None
    out = {}
    for l in lines[starts[-1]:]:
        m = ROW.match(l)
        if not m:
            break
        out[m.group(1)] = float(m.group(4))
    return out


res = {}
for ds in ('pv', 'eldds'):
    for n in NS:
        for init in ('src', 'coco'):
            log = FS / f'fs_{ds}_n{n}_{init}.log'
            v = final_val(log) if log.exists() else None
            if v:
                d = [v.get(c, 0.0) for c in CLASSES[ds]]
                res[f'{ds}_n{n}_{init}'] = {'all': v['all'], 'defect_mAP50': sum(d) / len(d),
                                            'per_class': dict(zip(CLASSES[ds], d))}
json.dump(res, open(FS / 'summary.json', 'w'), indent=1)

L = ['# Few-shot transfer', '', 'Generated by `code/repro/fewshot/summarize.py` (runs: `code/repro/fewshot/make_fewshot.py`). '
     'Defect-class mAP@.5 on the target\'s full evaluation split after fine-tuning on n target images (~1500 iterations, 640 px).', '']
for ds, title in (('pv', 'ELDDS → PV-Multi-Defect (P2 model, P2 recipe; PV val 222)'),
                  ('eldds', 'PV-Multi-Defect → ELDDS1400C5 (P1 model, P1 recipe; ELDDS test 190)')):
    L += [f'## {title}', '', f'| n target images | from {SRC[ds]} | from COCO | difference |', '|---|---|---|---|']
    for n in NS:
        a, b = res.get(f'{ds}_n{n}_src'), res.get(f'{ds}_n{n}_coco')
        f = lambda r: f"{r['defect_mAP50']:.3f}" if r else '—'  # noqa: E731
        diff = f"{a['defect_mAP50'] - b['defect_mAP50']:+.3f}" if a and b else ''
        L.append(f'| {n} | {f(a)} | {f(b)} | {diff} |')
    L += ['', f'Reference, home model on its full training set: {HOME[ds][0]}: {HOME[ds][1]:.3f}.', '']
(FS / 'summary.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('\n'.join(L))

# ---------------------------------------------------------------- figure
INK2, MUTED, GRID, BASE, SURF = '#52514e', '#898781', '#e1e0d9', '#c3c2b7', '#fcfcfb'
SC, CC = '#2a78d6', '#eb6834'
plt.rcParams.update({'font.family': 'sans-serif', 'font.size': 10, 'axes.edgecolor': BASE, 'axes.labelcolor': INK2,
                     'xtick.color': MUTED, 'ytick.color': MUTED, 'axes.titlecolor': '#0b0b0b', 'figure.facecolor': SURF,
                     'axes.facecolor': SURF, 'savefig.facecolor': SURF, 'axes.spines.top': False,
                     'axes.spines.right': False, 'legend.frameon': False, 'axes.titlesize': 10})
fig, axs = plt.subplots(1, 2, figsize=(8.2, 3.2), sharey=True)
for ax, ds, title in zip(axs, ('pv', 'eldds'), ('Target PV-Multi-Defect (P1 data)', 'Target ELDDS1400C5 (P2 data)')):
    for init, col, mk in (('src', SC, 'o'), ('coco', CC, 's')):
        pts = [(n, res[f'{ds}_n{n}_{init}']['defect_mAP50']) for n in NS if f'{ds}_n{n}_{init}' in res]
        if pts:
            ax.plot(*zip(*pts), color=col, lw=2, marker=mk, ms=7, mec=SURF, mew=1.5)
            ax.text(pts[-1][0] * 1.08, pts[-1][1], f'{pts[-1][1]:.2f}', va='center', fontsize=8, color=INK2)
    ax.axhline(HOME[ds][1], color=MUTED, lw=1, ls=(0, (3, 3)))
    ax.text(10, HOME[ds][1] + 0.015, f'home model, full data: {HOME[ds][1]:.2f}', fontsize=8, color=MUTED)
    ax.set_xscale('log')
    ax.set_xticks(NS)
    ax.set_xticklabels([str(n) for n in NS])
    ax.set_xlim(8, 140)
    ax.set_ylim(0, 1)
    ax.set_xlabel('labelled target images')
    ax.set_title(title, loc='left')
    ax.grid(axis='y', color=GRID, lw=0.6)
axs[0].set_ylabel('defect mAP@.5 on target test')
fig.legend(handles=[Line2D([], [], color=SC, marker='o', lw=2, label="start: the other paper's trained model"),
                    Line2D([], [], color=CC, marker='s', lw=2, label='start: COCO weights')],
           loc='lower center', ncol=2, bbox_to_anchor=(0.5, -0.1), fontsize=9, labelcolor=INK2)
fig.tight_layout()
fig.savefig(ROOT / 'results/cross/figs/fig11_fewshot.png', dpi=150, bbox_inches='tight')
