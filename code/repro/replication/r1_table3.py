"""P1 Table 3 (GBH-YOLOv5 vs five other methods), tested only by R1: R1's own evaluation JSONs on R1's val split
(its code; these models' predictions were not saved, so they cannot be re-scored with our evaluator).

usage (repo root): envs/p3cnn/Scripts/python.exe -I code/repro/replication/r1_table3.py <R1 folder>
-> results/replication_r1/p1_table3.md
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
RUNS = Path(sys.argv[1]) / 'elec_paper/GBH-YOLOv5/runs'
sys.stdout.reconfigure(encoding='utf-8')
ROWS = [  # method in the paper's Table 3, paper mAP@.5, R1 result file, R1 implementation
    ('Tommaso et al. (YOLOv3)', 57.9, 'eval/yolov3.json', 'YOLOv3 (GBH repo cfg), COCO init, 100 epochs, 600 px'),
    ('Girshick et al. (Faster R-CNN)', 69.3, 'baselines/frcnn.json', 'torchvision R50-FPN, COCO init, 40 epochs'),
    ('Mantel et al. (SVM)', 45.3, 'baselines/hog_svm.json', 'HOG + linear SVM, sliding window'),
    ('Almazroue et al. (Mask R-CNN)', 51.2, 'baselines/mrcnn.json', 'torchvision R50-FPN, box masks, COCO init, 40 epochs'),
    ('Ren et al. (SSD)', 30.8, 'baselines/ssd.json', 'torchvision SSD300-VGG16, 120 epochs'),
    ('GBH-YOLOv5 (proposed)', 97.8, 'eval/gbh.json', 'authors\' code, released yaml, 500 epochs, 600 px'),
]
L = ['# P1 Table 3: comparison methods (R1, R1 val split)', '', 'Generated by `code/repro/replication/r1_table3.py` from '
     'R1\'s evaluation files.', '', '| Method | Paper mAP@.5 | R1 mAP@.5 | R1 implementation |', '|---|---|---|---|']
res = {}
for name, paper, f, impl in ROWS:
    m = 100 * json.load(open(RUNS / f))['mAP50']
    res[name] = m
    L.append(f'| {name} | {paper} | {m:.1f} | {impl} |')
gbh = res['GBH-YOLOv5 (proposed)']
others = {k: v for k, v in res.items() if 'proposed' not in k}
best = max(others, key=others.get)
L += ['', f"Paper: GBH beats the others by at least 27.8 points (its own table gives 97.8 − 69.3 = 28.5). R1: the best other "
      f"method ({best}, {others[best]:.1f}) is {others[best] - gbh:+.1f} points vs GBH ({gbh:.1f}); "
      f"{sum(v > gbh for v in others.values())} of {len(others)} comparison methods score higher than GBH."]
(ROOT / 'results/replication_r1/p1_table3.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('\n'.join(L))
