"""P2 ablations (Tables 1-2: GAM-only, ASFF-only, DIoU-only) and seed spread (YOLOv5s and Improved, seeds 0-2).

Reads the yolov5 v7.0 val.py logs in results/p2/eval/ (test split, 190 images, 640 px; DIoU-NMS for the Improved
model and for DIoU-only, i.e. YOLOv5s weights re-evaluated with DIoU-NMS). Seed 0 = the main runs.

usage (repo root): envs/p3cnn/Scripts/python.exe -I code/repro/p2/ablation_seeds.py  -> results/p2/ablation_seeds.md
"""
import sys
from pathlib import Path

import numpy as np
from scipy import stats

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'code/repro'))
from summarize import EVAL, parse  # noqa: E402

sys.stdout.reconfigure(encoding='utf-8')
# paper Table 1 (mAP@.5, mAP@.5:.95) and Table 2 (mAP@.5 without / with TTA)
PAPER = {'v5s': (0.738, 0.502, 0.739, 0.766), 'v5_gam': (0.754, 0.511, 0.752, 0.775),
         'v5_asff': (0.751, 0.499, 0.74991, 0.766), 'v5s_diou': (0.744, 0.500, 0.74623, 0.772),
         'v5_improved': (0.763, 0.516, 0.76222, 0.777)}
LABEL = {'v5s': 'YOLOv5s', 'v5_gam': '+ GAM only', 'v5_asff': '+ ASFF only', 'v5s_diou': '+ DIoU-NMS only',
         'v5_improved': '+ GAM + ASFF + DIoU-NMS'}
L = ['# P2 ablations and seed spread', '', 'Generated by `code/repro/p2/ablation_seeds.py` from `results/p2/eval/*.log` '
     '(yolov5 v7.0 val.py, test split 190 images, 640 px).', '',
     '## Ablation (paper Tables 1–2), seed 0', '',
     '| Model | Paper mAP@.5 (T1) | Ours | Paper gain over YOLOv5s | Our gain | Paper mAP@.5 TTA | Ours TTA |',
     '|---|---|---|---|---|---|---|']
base = parse(EVAL / 'v5s_notta.log')
for k, (m50, m, t2, tta) in PAPER.items():
    r, rt = parse(EVAL / f'{k}_notta.log'), parse(EVAL / f'{k}_tta.log')
    if r is None:
        L.append(f'| {LABEL[k]} | {m50:.3f} | (not run) | | | {tta:.3f} | |')
        continue
    L.append(f"| {LABEL[k]} | {m50:.3f} | {r['map50']:.3f} | {m50 - PAPER['v5s'][0]:+.3f} | {r['map50'] - base['map50']:+.3f} | "
             f"{tta:.3f} | {rt['map50']:.3f} |" if rt else f"| {LABEL[k]} | {m50:.3f} | {r['map50']:.3f} | "
             f"{m50 - PAPER['v5s'][0]:+.3f} | {r['map50'] - base['map50']:+.3f} | {tta:.3f} | |")
L += ['', '## Seed spread (seeds 0, 1, 2; no TTA)', '', '| Model | seed 0 | seed 1 | seed 2 | mean ± sd |', '|---|---|---|---|---|']
vals = {}
for k in ('v5s', 'v5_improved'):
    v = [parse(EVAL / f'{k}{"" if s == 0 else f"_s{s}"}_notta.log') for s in (0, 1, 2)]
    v = [x['map50'] if x else None for x in v]
    vals[k] = [x for x in v if x is not None]
    ms = f'{np.mean(vals[k]):.3f} ± {np.std(vals[k], ddof=1):.3f}' if len(vals[k]) > 1 else ''
    L.append(f"| {LABEL[k]} | " + ' | '.join('—' if x is None else f'{x:.3f}' for x in v) + f' | {ms} |')
a, b = vals['v5_improved'], vals['v5s']
if len(a) > 1 and len(b) > 1:
    d = np.mean(a) - np.mean(b)
    t = stats.ttest_ind(a, b, equal_var=False)
    L += ['', f'Improved − YOLOv5s over seeds: **{d:+.3f}** (Welch t-test p = {t.pvalue:.2f}, n = {len(a)} / {len(b)}). '
          f'Paper: +{PAPER["v5_improved"][0] - PAPER["v5s"][0]:.3f} (Table 1), single run. Seed sd of YOLOv5s: '
          f'{np.std(b, ddof=1):.3f}, of Improved: {np.std(a, ddof=1):.3f}.']
(ROOT / 'results/p2/ablation_seeds.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('\n'.join(L))
