"""Write P2 model yamls from ultralytics v7.0 models/yolov5s.yaml.

GAM_Attention layers are inserted after the given layer indices (indices refer to the original
yolov5s.yaml) and all absolute 'from' references are re-indexed. ASFF swaps Detect for ASFF_Detect.

usage: python -I make_yamls.py --base code/yolov5-v7.0/models/yolov5s.yaml --out FILE \
           [--gam 9,17,20,23] [--gam-group] [--asff] [--nc 6]
"""
import argparse

import yaml

ap = argparse.ArgumentParser()
ap.add_argument('--base', required=True)
ap.add_argument('--out', required=True)
ap.add_argument('--gam', default='')
ap.add_argument('--gam-group', action='store_true')
ap.add_argument('--asff', action='store_true')
ap.add_argument('--nc', type=int, default=6)
a = ap.parse_args()

d = yaml.safe_load(open(a.base))
layers = d['backbone'] + d['head']
nb = len(d['backbone'])
after = sorted(int(i) for i in a.gam.split(',') if i)
new_idx, out = {}, []
for i, (f, n, m, args) in enumerate(layers):
    new_idx[i] = len(out)
    out.append([f, n, m, args])
    if i in after:
        c = layers[i][3][0] if layers[i][2] in ('Conv', 'C3', 'SPPF') else None
        assert c, f'cannot infer channels after layer {i}'
        out.append([-1, 1, 'GAM_Attention', [c, 4, a.gam_group]])
        new_idx[i] = len(out) - 1  # consumers of layer i now read the GAM output
remap = lambda f: f if f == -1 else new_idx[f]  # noqa: E731
for l in out:
    l[0] = [remap(x) for x in l[0]] if isinstance(l[0], list) else remap(l[0])
if a.asff:
    assert out[-1][2] == 'Detect'
    out[-1][2] = 'ASFF_Detect'
nb_new = new_idx[nb - 1] + 1
d['nc'] = a.nc
d['backbone'], d['head'] = out[:nb_new], out[nb_new:]
desc = f"# P2 re-implementation, generated by code/repro/p2/make_yamls.py from ultralytics v7.0 yolov5s.yaml\n" \
       f"# GAM after original layers {after or 'none'} (group={a.gam_group}); head={'ASFF_Detect' if a.asff else 'Detect'}\n"
flow = lambda k: '\n'.join(f'  - {yaml.safe_dump(l, default_flow_style=True).strip()}' for l in d[k])  # noqa: E731
body = {k: d[k] for k in ('nc', 'depth_multiple', 'width_multiple', 'anchors')}
open(a.out, 'w').write(desc + yaml.safe_dump(body, default_flow_style=None, sort_keys=False) +
                       f"backbone:\n{flow('backbone')}\nhead:\n{flow('head')}\n")
