"""Multiplicity correction for the 35 paired tests of paired_tests.py (COMPARISON.md §3.2).

The bootstrap p of paired_tests.json has a resolution of 1/1000, too coarse for 35 comparisons, so a continuous
p is taken from the bootstrap standard error (normal approximation, SE = CI width / 3.92) and Holm-adjusted
(family-wise error 0.05) over all 35, and separately within the 7 home-dataset tests.

usage (repo root): envs/p3cnn/Scripts/python.exe -I code/repro/cross/holm.py  -> results/cross/tables_holm.md
"""
import json
import sys
from pathlib import Path

import numpy as np
from scipy.stats import norm

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import DS_LABEL, MODELS, OUT  # noqa: E402

sys.stdout.reconfigure(encoding='utf-8')
T = json.load(open(OUT / 'paired_tests.json'))['paired']
for r in T:
    se = (r['ci'][1] - r['ci'][0]) / (2 * 1.959964)
    r['p_norm'] = float(2 * norm.sf(abs(r['diff']) / se)) if se > 0 else 0.0
    r['home'] = r['metric'].startswith('home') or (r['ds'] == MODELS[r['a']][1] and r['metric'] != 'mapped mAP@.5' and
                                                  r['metric'] in ('agnostic mAP@.5', 'tile AUC'))


def holm(ps):
    o = np.argsort(ps)
    adj, run = np.empty(len(ps)), 0.0
    for i, k in enumerate(o):
        run = max(run, (len(ps) - i) * ps[k])
        adj[k] = min(1.0, run)
    return adj


all_adj = holm(np.array([r['p_norm'] for r in T]))
home = [i for i, r in enumerate(T) if r['home']]
home_adj = dict(zip(home, holm(np.array([T[i]['p_norm'] for i in home]))))
L = ['### Paired tests with Holm correction (family-wise error 0.05)', '',
     'Generated by `code/repro/cross/holm.py`. p from the bootstrap SE (normal approximation). Bold = significant after '
     'Holm over all 35 tests.', '',
     '| A − B | metric | dataset | difference [95 % CI] | p | Holm p (35 tests) | Holm p (home only) |', '|---|---|---|---|---|---|---|']
for i, r in enumerate(T):
    s = '**' if all_adj[i] < 0.05 else ''
    h = f'{home_adj[i]:.3f}' if i in home_adj else ''
    L.append(f"| {MODELS[r['a']][0]} − {MODELS[r['b']][0]} | {r['metric']} | {DS_LABEL[r['ds']]} | "
             f"{s}{r['diff']:+.3f}{s} [{r['ci'][0]:+.3f}, {r['ci'][1]:+.3f}] | {r['p_norm']:.4f} | {all_adj[i]:.3f} | {h} |")
n_raw = sum(r['ci'][0] > 0 or r['ci'][1] < 0 for r in T)
L += ['', f'{n_raw} of {len(T)} CIs exclude 0; {int((all_adj < 0.05).sum())} remain significant after Holm over all {len(T)}; '
      f'{sum(v < 0.05 for v in home_adj.values())} of {len(home)} home tests after Holm within the home family.']
(OUT / 'tables_holm.md').write_text('\n'.join(L) + '\n', encoding='utf-8')
print('\n'.join(L))
